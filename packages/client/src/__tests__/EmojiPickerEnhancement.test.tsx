/**
 * EmojiPicker 拡充機能のユニットテスト
 *
 * テスト対象: packages/client/src/components/Chat/EmojiPicker.tsx
 * - 最近使った絵文字タブ
 * - スキントーン選択
 * - 絵文字名での検索
 * - カテゴリ別タブ / セクション
 */

import { describe, it } from 'vitest';

describe('EmojiPicker 拡充機能', () => {
  describe('最近使った絵文字タブ', () => {
    it.todo('「最近使った」タブが表示される');
    it.todo('直近で使用した絵文字が「最近使った」タブに表示される');
    it.todo('一度も使っていない場合は「最近使った」タブに何も表示されない');
    it.todo('絵文字を選択すると「最近使った」リストの先頭に追加される');
    it.todo('同じ絵文字を再度選択しても「最近使った」リストに重複して追加されない');
    it.todo('「最近使った」リストは上限件数を超えると古いものから削除される');
    it.todo('「最近使った」リストはページリロード後も保持される（localStorage など永続化）');
  });

  describe('スキントーン選択', () => {
    it.todo('人・手などのスキントーン対応絵文字でスキントーン選択UIが表示される');
    it.todo('スキントーンは 6 色（デフォルト含む）から選択できる');
    it.todo('スキントーンを選択すると対象絵文字がそのトーンで反映される');
    it.todo('スキントーンの選択状態はグローバルに保持される（他の絵文字にも適用される）');
    it.todo('スキントーン非対応の絵文字ではスキントーン選択UIが表示されない');
    it.todo('選択したスキントーンはページリロード後も保持される');
  });

  describe('絵文字名による検索', () => {
    it.todo('検索欄が表示される');
    it.todo('検索欄にテキストを入力すると絵文字名でフィルタリングされる');
    it.todo('検索結果が 0 件のとき「見つかりません」などのメッセージが表示される');
    it.todo('検索欄をクリアすると全絵文字が再表示される');
    it.todo('検索中はカテゴリタブ / セクションが非表示になる');
    it.todo('日本語での絵文字名検索が機能する');
  });

  describe('カテゴリ別タブ / セクション', () => {
    it.todo('スマイル・感情カテゴリのタブ / セクションが表示される');
    it.todo('動物カテゴリのタブ / セクションが表示される');
    it.todo('食べ物カテゴリのタブ / セクションが表示される');
    it.todo('旅行・場所カテゴリのタブ / セクションが表示される');
    it.todo('物・アクティビティカテゴリのタブ / セクションが表示される');
    it.todo('記号・フラグカテゴリのタブ / セクションが表示される');
    it.todo('カテゴリタブをクリックすると対応する絵文字群が表示される');
    it.todo('各カテゴリには少なくとも 1 つ以上の絵文字が含まれる');
  });
});
