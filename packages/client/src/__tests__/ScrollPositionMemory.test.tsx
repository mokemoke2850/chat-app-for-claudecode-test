/**
 * テスト対象: チャンネル切替時のスクロール位置記憶機能
 * 戦略:
 *   - MessageList / ChatPage / DMPage でのスクロール位置の保存・復元ロジックを検証する
 *   - containerRef の scrollTop を直接操作してスクロール状態を再現する
 *   - channelId / conversationId の変化をトリガーに保存・復元が実行されることを確認する
 *   - セッション内のインメモリ保持のみを対象とする（localStorage 永続化は対象外）
 */

import { describe, it } from 'vitest';

describe('スクロール位置記憶 — チャンネル切替', () => {
  describe('MessageList コンポーネント', () => {
    it.todo('channelId が変化したとき、離脱前の scrollTop を内部マップに保存する');
    it.todo('同じ channelId に戻ったとき、保存済み scrollTop を containerRef に復元する');
    it.todo('未訪問チャンネルに移動したとき、スクロール位置の復元をスキップして最下部へ移動する');
    it.todo('保存済みスクロール位置が最下部付近の場合、最下部に到達した状態で表示される');
    it.todo('messages が空（チャンネル切替直後）の間はスクロール復元を実行しない');
  });

  describe('ChatPage — チャンネル間の切替', () => {
    it.todo(
      'チャンネルAで中間スクロール後にチャンネルBへ切り替えると、Aのスクロール位置が保持される',
    );
    it.todo('チャンネルBからチャンネルAに戻ると、保存されたスクロール位置が自動的に復元される');
    it.todo('3チャンネル以上を順番に移動しても、それぞれのスクロール位置が独立して保持される');
    it.todo(
      'URL ?channel= パラメータの変化でチャンネルが切り替わったときもスクロール位置が保存・復元される',
    );
    it.todo('新着メッセージ受信後、最下部付近でなければスクロール位置が自動変更されない');
  });

  describe('DMPage — DM会話間の切替', () => {
    it.todo('会話Aで中間スクロール後に会話Bへ切り替えると、Aのスクロール位置が保持される');
    it.todo('会話Bから会話Aに戻ると、保存されたスクロール位置が自動的に復元される');
    it.todo('activeConvId が変化したとき、切替前の conversationId に対応する scrollTop を保存する');
  });

  describe('スレッドパネル', () => {
    it.todo(
      'スレッドを開いてスクロールした後、別のスレッドを開くと元スレッドのスクロール位置が保持される',
    );
    it.todo('同じスレッドを再度開いたとき、前回のスクロール位置が復元される');
  });

  describe('エッジケース', () => {
    it.todo('ページリロード後はスクロール位置がリセットされ最下部から表示される');
    it.todo('スクロール位置が 0（最上部）のチャンネルに戻ったとき、最上部が正しく表示される');
    it.todo('チャンネル切替時にメッセージロードが完了してからスクロール復元が実行される');
  });
});
