/**
 * テスト対象: pages/TaskBoardPage.tsx に追加するインライン作成機能（Issue #268）
 * 戦略:
 *   - 各カラム下部の「+ タスク追加」ボタン → 入力フィールド表示 → Enter で作成 / Esc でキャンセルの
 *     インライン作成 UX を検証する
 *   - api.tasks.create を vi.mock で差し替え、status を含む作成パラメータが正しく渡されるかを確認する
 *   - 詳細編集は引き続きモーダル経由のため、インライン作成の責務はタイトルのみの軽量作成に限定する
 *   - 既存 TaskBoardPage.test.tsx の DnD / モック構成を踏襲する
 */

import { describe, it } from 'vitest';

describe('TaskBoardPage インライン作成 (Issue #268)', () => {
  describe('「+ タスク追加」ボタンの表示', () => {
    it.todo('未着手カラムの下部に「+ タスク追加」ボタンが表示される');
    it.todo('進行中カラムの下部に「+ タスク追加」ボタンが表示される');
    it.todo('完了カラムの下部に「+ タスク追加」ボタンが表示される');
    it.todo('初期表示時は入力フィールドではなくボタンとしてレンダーされる');
  });

  describe('入力フィールドの開閉', () => {
    it.todo('「+ タスク追加」ボタンをクリックするとそのカラムだけ入力フィールドが表示される');
    it.todo('入力フィールド表示中はそのカラムの「+ タスク追加」ボタンが非表示になる');
    it.todo(
      '別カラムの「+ タスク追加」ボタンをクリックしても他カラムの入力フィールドは閉じない（独立して開閉できる）',
    );
    it.todo('入力フィールドにオートフォーカスが当たる');
  });

  describe('Enter による作成', () => {
    it.todo('タイトルを入力して Enter を押すと api.tasks.create が呼ばれる');
    it.todo('未着手カラムで作成した場合 status: "todo" で作成される');
    it.todo('進行中カラムで作成した場合 status: "in_progress" で作成される');
    it.todo('完了カラムで作成した場合 status: "done" で作成される');
    it.todo('作成成功後にタスク一覧が再フェッチされる');
    it.todo('作成成功後に入力フィールドの値がクリアされる');
    it.todo('作成成功後も入力フィールドは開いたままで連続入力できる');
    it.todo('タイトルが空白のみの場合は Enter を押しても api.tasks.create が呼ばれない');
    it.todo('タイトルの前後の空白はトリムされて送信される');
    it.todo('IME 変換確定の Enter（isComposing: true）では作成が実行されない');
  });

  describe('Esc によるキャンセル', () => {
    it.todo('Esc キーを押すと入力フィールドが閉じる');
    it.todo('Esc キーを押すと入力中のテキストが破棄される（再度開いたとき空になる）');
    it.todo('Esc キーを押しても api.tasks.create は呼ばれない');
  });

  describe('フォーカス喪失時の挙動', () => {
    it.todo('入力フィールドからフォーカスが外れたとき、空のままなら入力フィールドを閉じる');
    it.todo('入力フィールドからフォーカスが外れても、入力テキストがあれば閉じずに残る');
  });

  describe('エラー時の挙動', () => {
    it.todo('api.tasks.create が失敗してもクラッシュせずエラーが UI に表示される');
    it.todo('作成失敗時は入力テキストがクリアされず、再 Enter で再送信できる');
  });

  describe('既存モーダル作成との共存', () => {
    it.todo('インライン作成と既存「新規タスク作成」ボタン（モーダル）の両方が同時に利用可能である');
    it.todo('インライン作成は CreateTaskDialog を開かない（ダイアログが DOM に出現しない）');
  });
});
