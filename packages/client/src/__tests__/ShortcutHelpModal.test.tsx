/**
 * テスト対象: ShortcutHelpModal コンポーネント（新規実装予定）
 *
 * 戦略:
 *   - キーボードイベント（?、Cmd+/、Ctrl+/、Escape）によるモーダル開閉を検証する
 *   - エディタフォーカス中は ? キーを無効化することを確認する
 *   - モーダルにカテゴリ別ショートカット一覧が表示されることを確認する
 *   - 各ショートカットのキー表記と説明文が正しく表示されることを確認する
 *   - jsdom 環境で動作するため、window.addEventListener でのキーイベントを userEvent.keyboard で発火する
 *   - ショートカットカタログが 1 箇所にまとまっていることを構造面から確認する
 */

import { describe, it } from 'vitest';

describe('ShortcutHelpModal', () => {
  describe('モーダルの開閉', () => {
    it.todo('? キーを押すとモーダルが開く');
    it.todo('Cmd+/ でモーダルが開く');
    it.todo('Ctrl+/ でモーダルが開く');
    it.todo('モーダルが開いているときに ? キーを押すと閉じる');
    it.todo('モーダルが開いているときに Escape キーを押すと閉じる');
    it.todo('モーダルが開いているときに Cmd+/ を押すと閉じる');
  });

  describe('エディタフォーカス中の無効化', () => {
    it.todo('isEditorFocused が true のとき ? キーでモーダルが開かない');
    it.todo('isEditorFocused が true のとき Cmd+/ でモーダルが開く（エディタ内でも有効）');
  });

  describe('カテゴリ別ショートカット表示', () => {
    it.todo('モーダル内にナビゲーションカテゴリが表示される');
    it.todo('モーダル内にメッセージ操作カテゴリが表示される');
    it.todo('モーダル内にエディタ・送信カテゴリが表示される');
  });

  describe('ショートカット一覧の内容（#255 / #257 / Quill 由来）', () => {
    it.todo('Cmd+K のショートカットとコマンドパレットの説明が表示される（#255）');
    it.todo('j / k のショートカットとメッセージ移動の説明が表示される（#257）');
    it.todo('Enter のショートカットとスレッドを開く説明が表示される（#257）');
    it.todo('r のショートカットとリアクションの説明が表示される（#257）');
    it.todo('p のショートカットとピン留めの説明が表示される（#257）');
    it.todo('Enter のショートカットとメッセージ送信の説明が表示される（Quill 由来）');
    it.todo('Shift+Enter のショートカットと改行の説明が表示される（Quill 由来）');
  });

  describe('ショートカットカタログの設計', () => {
    it.todo('ショートカット定義が 1 箇所のカタログ配列（SHORTCUTS 等）からインポートされている');
    it.todo('カタログ配列に category / keys / description のフィールドが存在する');
  });
});
