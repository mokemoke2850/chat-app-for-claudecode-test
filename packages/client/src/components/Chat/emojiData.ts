export const CATEGORIES: EmojiCategory[] = ['スマイル', '動物', '食べ物', '旅行', '物', '記号'];

export function getEmojisByCategory(category: EmojiCategory): EmojiEntry[] {
  return EMOJI_DATA.filter((e) => e.category === category);
}

export function searchEmojis(query: string): EmojiEntry[] {
  const q = query.toLowerCase();
  return EMOJI_DATA.filter(
    (e) => e.name.toLowerCase().includes(q) || e.nameJa.includes(query) || e.emoji.includes(query),
  );
}

export function applySkintone(emoji: string, skinToneIndex: SkinToneIndex): string {
  return emoji + SKIN_TONES[skinToneIndex];
}

export const RECENT_EMOJI_KEY = 'emoji-recent';
export const SKIN_TONE_KEY = 'emoji-skin-tone';
export const MAX_RECENT = 20;

export function loadRecentEmojis(): string[] {
  try {
    return JSON.parse(localStorage.getItem(RECENT_EMOJI_KEY) ?? '[]');
  } catch {
    return [];
  }
}

export function saveRecentEmoji(emoji: string, current: string[]): string[] {
  const next = [emoji, ...current.filter((e) => e !== emoji)].slice(0, MAX_RECENT);
  localStorage.setItem(RECENT_EMOJI_KEY, JSON.stringify(next));
  return next;
}

export function loadSkinTone(): SkinToneIndex {
  const stored = localStorage.getItem(SKIN_TONE_KEY);
  const idx = stored !== null ? parseInt(stored, 10) : 0;
  if (idx >= 0 && idx <= 5) return idx as SkinToneIndex;
  return 0;
}

export function saveSkinTone(index: SkinToneIndex): void {
  localStorage.setItem(SKIN_TONE_KEY, String(index));
}
